# 应用规则：只处理「正确项为唯一最长」的题；扩写干扰项直到 ≥ 正确项长度
files = sorted(glob.glob("app/src/main/assets/questions/*.json")) + sorted(
    glob.glob("update-server/packs/src/*.json")
)
fixed_count = 0
remaining = []
for path in files:
    d = json.load(open(path, encoding="utf-8"))
    changed = False
    for q in d.get("questions", []):
        if q.get("type", "single") != "single" or len(q["options"]) != 4:
            continue
        lens = [len(o) for o in q["options"]]
        ans = q["answer"]
        others = [l for i, l in enumerate(lens) if i != ans]
        if lens[ans] <= max(others):
            continue
        need = lens[ans]
        # 依次尝试扩写每个短干扰项
        for i, opt in enumerate(q["options"]):
            if i == ans:
                continue
            rep = DICT.get(opt.strip())
            if rep and len(rep) >= need:
                q["options"][i] = rep
                changed = True
                fixed_count += 1
                break
        # 复查
        lens2 = [len(o) for o in q["options"]]
        others2 = [l for i, l in enumerate(lens2) if i != ans]
        if lens2[ans] > max(others2):
            remaining.append({"file": path.split("/")[-1].split("\\")[-1], "id": q["id"],
                              "lens": lens2, "opts": q["options"], "q": q["question"][:36], "ans": ans})
    if changed:
        json.dump(d, open(path, "w", encoding="utf-8"), ensure_ascii=False, indent=2)

json.dump(remaining, open("tools/audit_remaining.json", "w", encoding="utf-8"), ensure_ascii=False, indent=1)
print(f"自动修复 {fixed_count} 题；剩余需手工 {len(remaining)} 题（清单在 tools/audit_remaining.json）")
